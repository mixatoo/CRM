import fs from 'node:fs'
import path from 'node:path'
import { fileURLToPath } from 'node:url'

const __dirname = path.dirname(fileURLToPath(import.meta.url))
const root = path.resolve(__dirname, '..')

const candidates = [
  process.env.BALOO_BHAIJAAN_2_TTF,
  path.join(root, 'src', 'assets', 'fonts', 'baloo-bhaijaan-2', 'BalooBhaijaan2-Variable.ttf'),
].filter(Boolean)

function resolveFont(paths) {
  for (const candidate of paths) {
    if (candidate && fs.existsSync(candidate)) return candidate
  }
  return null
}

const fontPath = resolveFont(candidates)
if (!fontPath) {
  console.error(
    'Baloo Bhaijaan 2 font not found. Download BalooBhaijaan2-Variable.ttf to src/assets/fonts/baloo-bhaijaan-2/ or set BALOO_BHAIJAAN_2_TTF.',
  )
  process.exit(1)
}

const fontBase64 = fs.readFileSync(fontPath, { encoding: 'base64' })

const output = `/* Auto-generated by scripts/generate-baloo-fonts.mjs — do not edit manually */
import type { jsPDF } from 'jspdf'

const BALOO_BHAIJAAN_2 = ${JSON.stringify(fontBase64)}

let registeredDocs = new WeakSet<object>()

export const PDF_FONT_FAMILY = 'BalooBhaijaan2'

/** Register Baloo Bhaijaan 2 (embedded) for normal + bold styles. */
export function registerPdfFonts(doc: jsPDF): void {
  if (registeredDocs.has(doc)) return
  doc.addFileToVFS('BalooBhaijaan2.ttf', BALOO_BHAIJAAN_2)
  doc.addFont('BalooBhaijaan2.ttf', PDF_FONT_FAMILY, 'normal')
  doc.addFont('BalooBhaijaan2.ttf', PDF_FONT_FAMILY, 'bold')
  registeredDocs.add(doc)
}
`

const outPath = path.join(root, 'src', 'assets', 'fonts', 'baloo-bhaijaan-2-fonts.ts')
fs.mkdirSync(path.dirname(outPath), { recursive: true })
fs.writeFileSync(outPath, output, 'utf8')
console.log(`Wrote ${outPath}`)
