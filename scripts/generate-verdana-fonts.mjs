import fs from 'node:fs'
import path from 'node:path'
import { fileURLToPath } from 'node:url'

const __dirname = path.dirname(fileURLToPath(import.meta.url))
const root = path.resolve(__dirname, '..')

const candidates = [
  process.env.VERDANA_TTF,
  'C:/Windows/Fonts/verdana.ttf',
  'C:/Windows/Fonts/VERDANA.TTF',
].filter(Boolean)

const boldCandidates = [
  process.env.VERDANA_BOLD_TTF,
  'C:/Windows/Fonts/verdanab.ttf',
  'C:/Windows/Fonts/VERDANAB.TTF',
].filter(Boolean)

function resolveFont(paths) {
  for (const candidate of paths) {
    if (candidate && fs.existsSync(candidate)) return candidate
  }
  return null
}

const normalPath = resolveFont(candidates)
const boldPath = resolveFont(boldCandidates)

if (!normalPath || !boldPath) {
  console.error('Verdana font files not found. Set VERDANA_TTF and VERDANA_BOLD_TTF env vars.')
  process.exit(1)
}

const normal = fs.readFileSync(normalPath, { encoding: 'base64' })
const bold = fs.readFileSync(boldPath, { encoding: 'base64' })

const output = `/* Auto-generated by scripts/generate-verdana-fonts.mjs — do not edit manually */
import type { jsPDF } from 'jspdf'

const VERDANA_NORMAL = ${JSON.stringify(normal)}
const VERDANA_BOLD = ${JSON.stringify(bold)}

let registeredDocs = new WeakSet<object>()

export function registerVerdanaFonts(doc: jsPDF): void {
  if (registeredDocs.has(doc)) return
  doc.addFileToVFS('Verdana.ttf', VERDANA_NORMAL)
  doc.addFont('Verdana.ttf', 'Verdana', 'normal')
  doc.addFileToVFS('Verdana-Bold.ttf', VERDANA_BOLD)
  doc.addFont('Verdana-Bold.ttf', 'Verdana', 'bold')
  registeredDocs.add(doc)
}

export const INVOICE_PDF_FONT = 'Verdana'
`

const outDir = path.join(root, 'src', 'assets', 'fonts')
fs.mkdirSync(outDir, { recursive: true })
fs.writeFileSync(path.join(outDir, 'verdana-fonts.ts'), output, 'utf8')
console.log(`Wrote ${path.join(outDir, 'verdana-fonts.ts')}`)
